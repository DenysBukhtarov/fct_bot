        f"👤 Володілець даних: {_v('PRIVACY_OWNER')}\n"
        "🎯 Мета: запис, зв'язок з вами, облік оплат і абонементів, нагадування.\n"
        "🗄 Зберігання: захищена база даних (сервери в ЄС). Дані не продаються і не передаються для реклами.\n\n"
